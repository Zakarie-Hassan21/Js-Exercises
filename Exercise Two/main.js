let x = 15;
let y = "15";

// Equal To 
console.log(x == y);
// Not Equal To 
console.log(x != y);
// Strictly Equal To 
console.log(x === y);
// Strictly Not Equal To
console.log(x !== y);
// Greater Than
console.log(x > y);
// Less Than 
console.log(x < y);
// Greater Than Or Equal 
console.log(x >= y);
// Less Than Or Equal 
console.log(x <= y);
